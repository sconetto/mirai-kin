export type FlatToken = {
  name: string;
  light: string;
  dark: string;
};

type TokenLeaf = {
  $value?: unknown;
  $extensions?: Record<string, string>;
};

function isTokenLeaf(value: unknown): value is TokenLeaf {
  return Boolean(value && typeof value === "object" && "$value" in value);
}

export function flattenTokens(document: Record<string, unknown>): FlatToken[] {
  const tokens: FlatToken[] = [];
  const seen = new Set<string>();

  const walk = (node: Record<string, unknown>, path: string[]) => {
    if (isTokenLeaf(node)) {
      const name = path.join("-");
      if (!name) throw new Error("Token is missing a path");
      if (seen.has(name)) throw new Error(`Duplicate token: ${name}`);
      seen.add(name);
      const light = String(node.$value);
      const dark = node.$extensions?.["mirai.dark"];
      tokens.push({ name, light, dark: dark === undefined ? light : String(dark) });
      return;
    }

    for (const [key, value] of Object.entries(node)) {
      if (key.startsWith("$")) continue;
      if (value && typeof value === "object") {
        walk(value as Record<string, unknown>, [...path, key]);
      }
    }
  };

  walk(document, []);
  return tokens;
}

export function buildTokenCss(document: Record<string, unknown>): string {
  const tokens = flattenTokens(document);
  if (tokens.length === 0) throw new Error("No design tokens found");

  const root = tokens.map((token) => `  --${token.name}: ${token.light};`);
  const dark = tokens.map((token) => `  --${token.name}: ${token.dark};`);

  return [
    "/* AUTO-GENERATED by pnpm tokens:build. Do not edit directly. */",
    ":root {",
    "  color-scheme: light;",
    ...root,
    "}",
    "",
    'html[data-theme="dark"] {',
    "  color-scheme: dark;",
    ...dark,
    "}",
    "",
  ].join("\n");
}
