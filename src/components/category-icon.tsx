export function CategoryIcon({
  name,
  icon,
  color,
  className,
}: {
  name: string;
  icon?: string | null;
  color?: string | null;
  className?: string;
}) {
  const key = (icon && ICON_MAP[icon as IconKey] ? icon : NAME_MAP[name.toLowerCase()]) ?? "tag";
  const Icon = ICON_MAP[key as IconKey] ?? Tag;
  return (
    <span
      className={cn("inline-flex shrink-0 items-center justify-center text-ink-3", className)}
      style={color ? { color } : undefined}
      aria-hidden="true"
    >
      <Icon className="h-3.5 w-3.5" />
    </span>
  );
}
